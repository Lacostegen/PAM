        private const double MinSchemeScale = 0.35;
        private const double MaxSchemeScale = 3.0;
        private const double SchemeScaleStep = 0.1;

        private double _schemeScale = 1.0;
        private bool _isSchemeVisible;

        public ViolatorView()
        {
            InitializeComponent();
        }

        private void ViolatorView_Loaded(object sender, RoutedEventArgs e)
        {
            if (DataContext is ViolatorViewModel viewModel)
            {
                viewModel.EnsureSelection();
            }

            ViolatorIdentifiersListBox.Items.Refresh();
        }

        private void ToggleSchemeButton_Click(object sender, RoutedEventArgs e)
        {
            SetSchemeVisible(!_isSchemeVisible);
        }

        private void HideSchemeButton_Click(object sender, RoutedEventArgs e)
        {
            SetSchemeVisible(false);
        }

        private void SetSchemeVisible(bool isVisible)
        {
            _isSchemeVisible = isVisible;

            ViolatorCardsPanel.Visibility = isVisible
                ? Visibility.Collapsed
                : Visibility.Visible;

            ViolatorSchemePanel.Visibility = isVisible
                ? Visibility.Visible
                : Visibility.Collapsed;

            SchemeToggleButton.Content = isVisible
                ? "Карточка нарушителя"
                : "Схема модели нарушителей";

            if (!isVisible)
            {
                Dispatcher.BeginInvoke(new Action(() =>
                {
                    if (DataContext is ViolatorViewModel viewModel)
                    {
                        viewModel.EnsureSelection();
                    }

                    ViolatorIdentifiersListBox.Items.Refresh();
                }), DispatcherPriority.Loaded);
            }
        }

        private void SchemeScrollViewer_PreviewMouseWheel(object sender, MouseWheelEventArgs e)
        {
            if (e.Delta > 0)
            {
                ChangeSchemeScale(SchemeScaleStep);
            }
            else
            {
                ChangeSchemeScale(-SchemeScaleStep);
            }

            e.Handled = true;
        }

        private void ResetSchemeZoomButton_Click(object sender, RoutedEventArgs e)
        {
            _schemeScale = 1.0;
            ApplySchemeScale();
        }

        private void ChangeSchemeScale(double delta)
        {
            _schemeScale += delta;

            if (_schemeScale < MinSchemeScale)
            {
                _schemeScale = MinSchemeScale;
            }

            if (_schemeScale > MaxSchemeScale)
            {
                _schemeScale = MaxSchemeScale;
            }

            ApplySchemeScale();
        }

        private void ApplySchemeScale()
        {
            SchemeScaleTransform.ScaleX = _schemeScale;
            SchemeScaleTransform.ScaleY = _schemeScale;
        }

        private void SchemeNodeButton_Click(object sender, RoutedEventArgs e)
        {
            if (sender is not Button button)
            {
                return;
            }

            var nodeName = button.Tag?.ToString() ?? "Неизвестный блок";
            SchemeNodeInfoTitle.Text = nodeName;
            SchemeNodeInfoDescription.Text = GetViolatorNodeDescription(nodeName);
        }

        private static string GetViolatorNodeDescription(string nodeName)
        {
            if (ViolatorNodeDescriptions.TryGetValue(nodeName, out var description))
            {
                return description;
            }

            if (nodeName.Contains("Администратор", StringComparison.OrdinalIgnoreCase))
            {
                return "Администратор относится к внутренним нарушителям с повышенным уровнем доступа. Для такого узла важно учитывать объем полномочий, возможность изменения конфигурации, доступ к журналам и способность отключать средства защиты.";
            }

            if (nodeName.Contains("Пользователь", StringComparison.OrdinalIgnoreCase))
            {
                return "Пользовательский узел описывает внутренний источник риска. Он может быть преднамеренным нарушителем, ошибиться из-за невнимательности или стать точкой входа после компрометации учетной записи.";
            }

            if (nodeName.Contains("групп", StringComparison.OrdinalIgnoreCase) ||
                nodeName.Contains("организац", StringComparison.OrdinalIgnoreCase) ||
                nodeName.Contains("подраздел", StringComparison.OrdinalIgnoreCase))
            {
                return "Этот узел относится к организованным субъектам угроз. При анализе важно оценивать ресурсы, координацию, устойчивость методов, мотивацию и возможный потенциал воздействия на организацию.";
            }

            if (nodeName.Contains("выгода", StringComparison.OrdinalIgnoreCase) ||
                nodeName.Contains("шпионаж", StringComparison.OrdinalIgnoreCase) ||
                nodeName.Contains("информац", StringComparison.OrdinalIgnoreCase))
            {
                return "Этот узел раскрывает мотивацию или объект интереса нарушителя. Он помогает понять, зачем выполняется атака и какие активы организации требуют первоочередной защиты.";
            }

            return $"Узел «{nodeName}» используется для классификации нарушителя в модели. Его следует учитывать при определении источника угрозы, мотивации, уровня доступа и возможных последствий для информационной системы.";
        }
